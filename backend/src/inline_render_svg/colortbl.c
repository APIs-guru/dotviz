static int schemecmpf(const void *p0, const void *p1) {
  return strcasecmp(p0, ((const colorscheme_t *)p1)->name);
}

static int colorcmpf(const void *p0, const void *p1) {
  return strcasecmp(p0, ((const hsvrgbacolor_t *)p1)->name);
}

static const hsvrgbacolor_t *findColor(char const* schemeName, char const *colorName) {
  const colorscheme_t *scheme =
      bsearch(schemeName, color_lib, sizeof(color_lib) / sizeof(colorscheme_t),
              sizeof(color_lib[0]), schemecmpf);
  if (scheme == NULL)
    return NULL;

  const hsvrgbacolor_t *colors = scheme->colors;
  size_t num_colors = scheme->num_colors;
  return bsearch(colorName, colors, num_colors, sizeof(colors[0]), colorcmpf);
}

static char *globalColorScheme = NULL;
char *setColorScheme(const char *s) {
  char *previous = globalColorScheme;
  globalColorScheme = s == NULL ? NULL : gv_strdup(s);
  return previous;
}

/* resolveColor:
 * Resolve input color str allowing color scheme namespaces.
 *  0) "black" => "black"
 *     "white" => "white"
 *     "lightgrey" => "lightgrey"
 *    NB: This is something of a hack due to the remaining codegen.
 *        Once these are gone, this case could be removed and all references
 *        to "black" could be replaced by "/X11/black".
 *  1) No initial / =>
 *          if colorscheme is defined and no "X11", return /colorscheme/str
 *          else return str
 *  2) One initial / => return str+1
 *  3) Two initial /'s =>
 *       a) If colorscheme is defined and not "X11", return /colorscheme/(str+2)
 *       b) else return (str+2)
 *  4) Two /'s, not both initial => return str.
 *
 * Note that 1), 2), and 3b) allow the default X11 color scheme.
 *
 * In other words,
 *   xxx => /colorscheme/xxx     if colorscheme is defined and not "X11"
 *   xxx => xxx                  otherwise
 *   /xxx => xxx
 *   /X11/yyy => yyy
 *   /xxx/yyy => /xxx/yyy
 *   //yyy => /colorscheme/yyy   if colorscheme is defined and not "X11"
 *   //yyy => yyy                otherwise
 *
 * At present, no other error checking is done. For example,
 * yyy could be "". This will be caught later.
 */
hsvrgbacolor_t const *resolveColor(const char *str) {
  if (!strcmp(str, "black"))
    return findColor("X11", str);
  if (!strcmp(str, "white"))
    return findColor("X11", str);
  if (!strcmp(str, "lightgrey"))
    return findColor("X11", str);

  const char *colorScheme = globalColorScheme;
  if (colorScheme == NULL || *colorScheme == '\0') {
    colorScheme = "X11";
  }

  if (str[0] == '/') {
    if (str[1] == '/') {
      return findColor(colorScheme, &str[2]);
    }
    char const* secondSlash = strchr(&str[1], '/');
    if (secondSlash == NULL) {
      return findColor("X11", str);
    }

    char* schemeName = strndup(&str[1], secondSlash - &str[1]);
    hsvrgbacolor_t const* color = findColor(schemeName, secondSlash + 1);
    free(schemeName);
    return color;
  }
  return findColor(colorScheme, str);
}
